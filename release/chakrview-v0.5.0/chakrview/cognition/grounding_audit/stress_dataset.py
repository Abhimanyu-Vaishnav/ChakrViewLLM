"""
Wave 568 & 569: 100-Case Grounding Stress & Scale Benchmark Suite.

Requirements:
- Scales evaluation to 100 independently constructed test cases across 8 diverse domains:
  1. Quantitative physical constants / metrics
  2. Temporal validity & freshness intervals
  3. Relational bindings across biological / organizational domains
  4. Multi-hop deductive chains (2, 3, 4 hops)
  5. Contradiction & polarization probes
  6. Partial / overclaiming boundaries
  7. Wrong-entity distractors
  8. Irrelevant distractors & noise
- Partitions:
  TRAIN/PRACTICE: 20 cases
  DEVELOPMENT: 20 cases
  FINAL_EVALUATION: 60 cases (strictly held-out, zero tuning contamination)
- Prevents test-harness self-fulfillment: Expected answers and classifications
  are statically authored fixtures, NOT generated by the implementation's own evaluator.
"""

from __future__ import annotations

import hashlib
from enum import Enum
from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional, Tuple


class GroundingDomain(str, Enum):
    QUANTITATIVE_PHYSICAL = "QUANTITATIVE_PHYSICAL"
    TEMPORAL_FRESHNESS = "TEMPORAL_FRESHNESS"
    ENTITY_RELATION = "ENTITY_RELATION"
    MULTIHOP_DEDUCTION = "MULTIHOP_DEDUCTION"
    CONTRADICTION_DEADLOCK = "CONTRADICTION_DEADLOCK"
    PARTIAL_OVERCLAIM = "PARTIAL_OVERCLAIM"
    WRONG_ENTITY_DISTRACTOR = "WRONG_ENTITY_DISTRACTOR"
    IRRELEVANT_NOISE = "IRRELEVANT_NOISE"


class GroundingPartition(str, Enum):
    PRACTICE = "PRACTICE"
    DEVELOPMENT = "DEVELOPMENT"
    FINAL_EVALUATION = "FINAL_EVALUATION"


@dataclass
class GroundingTestCase:
    test_id: str
    domain: GroundingDomain
    partition: GroundingPartition
    query: str
    target_entity: str
    target_relation: str
    evidence_payload: List[Dict[str, Any]]
    expected_decision: str       # ANSWER, ABSTAIN, REPORT_CONFLICT, QUALIFY
    expected_value_token: Optional[str]
    expected_epistemic_state: str # KNOWN, UNKNOWN, CONFLICTING, PARTIALLY_SUPPORTED
    expected_is_overclaim_blocked: bool = False
    is_counterfactual_case: bool = False
    counterfactual_value: Optional[str] = None


@dataclass
class GroundingStressBenchmark:
    benchmark_id: str
    total_cases: int
    practice_cases: List[GroundingTestCase]
    dev_cases: List[GroundingTestCase]
    final_eval_cases: List[GroundingTestCase]


def build_100_case_grounding_benchmark() -> GroundingStressBenchmark:
    cases: List[GroundingTestCase] = []

    # Domain 1: Quantitative Physical Metrics (15 cases)
    planets = [
        ("Mercury", "orbital period", "88 days"),
        ("Venus", "surface temp", "465 C"),
        ("Mars", "diameter", "6,779 km"),
        ("Jupiter", "mass", "1.898e27 kg"),
        ("Saturn", "orbital period", "29.5 years"),
        ("Uranus", "axial tilt", "97.8 degrees"),
        ("Neptune", "wind speed", "2,100 km/h"),
        ("Ceres", "diameter", "940 km"),
        ("Eris", "orbital period", "558 years"),
        ("Makemake", "distance from Sun", "45.8 AU"),
        ("Haumea", "rotation period", "3.9 hours"),
        ("Titan", "atmospheric pressure", "1.5 bar"),
        ("Europa", "ocean depth", "100 km"),
        ("Ganymede", "magnetic field", "present"),
        ("Enceladus", "geyser content", "water vapor"),
    ]
    for idx, (ent, rel, val) in enumerate(planets):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 5 else (GroundingPartition.DEVELOPMENT if idx >= 2 else GroundingPartition.PRACTICE)
        cases.append(GroundingTestCase(
            test_id=f"quant_{idx:02d}",
            domain=GroundingDomain.QUANTITATIVE_PHYSICAL,
            partition=part,
            query=f"What is the {rel} of {ent}?",
            target_entity=ent,
            target_relation=rel,
            evidence_payload=[{"entity": ent, "relation": rel, "value": val, "text": f"{ent} {rel} is {val}.", "polarity": True, "confidence": 0.95}],
            expected_decision="ANSWER",
            expected_value_token=val,
            expected_epistemic_state="KNOWN",
        ))

    # Domain 2: Temporal Freshness & Staleness (15 cases)
    temporal_entities = [
        ("TechCorp Alpha", "version release", "v4.2", True, "CURRENT"),
        ("OldCorp Beta", "CEO", "John Doe", False, "STALE"),
        ("Protocol Gamma", "active status", "deprecated", False, "HISTORICAL"),
        ("GovAgency Delta", "treaty status", "ratified", True, "CURRENT"),
        ("Standard Epsilon", "compliance year", "2019", False, "STALE"),
        ("Framework Zeta", "LTS build", "v2.0", True, "CURRENT"),
        ("Consortium Eta", "lead chair", "Alice Smith", True, "CURRENT"),
        ("Treaty Theta", "enforcement date", "expired in 2020", False, "HISTORICAL"),
        ("Product Iota", "price tier", "$99/mo", True, "CURRENT"),
        ("License Kappa", "royalty term", "active", True, "CURRENT"),
        ("Alliance Lambda", "member count", "12 members", True, "CURRENT"),
        ("Directive Mu", "annual quota", "1000 units", False, "STALE"),
        ("Accord Nu", "validity year", "valid until 2018", False, "HISTORICAL"),
        ("Initiative Xi", "budget cap", "$5M", True, "CURRENT"),
        ("Registry Omicron", "certificate hash", "valid_cert", True, "CURRENT"),
    ]
    for idx, (ent, rel, val, is_curr, exp_t) in enumerate(temporal_entities):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 5 else (GroundingPartition.DEVELOPMENT if idx >= 2 else GroundingPartition.PRACTICE)
        exp_dec = "ANSWER" if is_curr else "ABSTAIN"
        exp_epist = "KNOWN" if is_curr else "UNKNOWN"
        cases.append(GroundingTestCase(
            test_id=f"tempo_{idx:02d}",
            domain=GroundingDomain.TEMPORAL_FRESHNESS,
            partition=part,
            query=f"What is current {rel} of {ent}?",
            target_entity=ent,
            target_relation=rel,
            evidence_payload=[{"entity": ent, "relation": rel, "value": val, "text": f"{ent} {rel} was {val}.", "is_time_varying": True, "is_stale": not is_curr}],
            expected_decision=exp_dec,
            expected_value_token=val if is_curr else None,
            expected_epistemic_state=exp_epist,
        ))

    # Domain 3: Entity Relations across Biology & Academia (15 cases)
    for idx in range(15):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 5 else (GroundingPartition.DEVELOPMENT if idx >= 2 else GroundingPartition.PRACTICE)
        ent = f"Organism_X{idx}"
        rel = "phylum classification"
        val = f"Clade_Y{idx}"
        cases.append(GroundingTestCase(
            test_id=f"rel_{idx:02d}",
            domain=GroundingDomain.ENTITY_RELATION,
            partition=part,
            query=f"What is the {rel} of {ent}?",
            target_entity=ent,
            target_relation=rel,
            evidence_payload=[{"entity": ent, "relation": rel, "value": val, "text": f"{ent} is classified in {val}.", "polarity": True}],
            expected_decision="ANSWER",
            expected_value_token=val,
            expected_epistemic_state="KNOWN",
        ))

    # Domain 4: Multi-Hop Chains (15 cases: 10 valid complete, 5 broken)
    for idx in range(15):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 5 else (GroundingPartition.DEVELOPMENT if idx >= 2 else GroundingPartition.PRACTICE)
        is_broken = (idx % 3 == 0)
        ent_start = f"Node_A{idx}"
        ent_mid = f"Node_B{idx}"
        ent_end = f"Node_C{idx}"
        
        if is_broken:
            # Broken link
            payload = [
                {"source_entity": ent_start, "relation": "leads_to", "target_entity": ent_mid},
                {"source_entity": f"Distractor_Z{idx}", "relation": "leads_to", "target_entity": ent_end}, # Mismatch!
            ]
            exp_dec = "ABSTAIN"
            exp_epist = "UNKNOWN"
            val_token = None
        else:
            payload = [
                {"source_entity": ent_start, "relation": "leads_to", "target_entity": ent_mid},
                {"source_entity": ent_mid, "relation": "leads_to", "target_entity": ent_end},
            ]
            exp_dec = "ANSWER"
            exp_epist = "KNOWN"
            val_token = ent_end

        cases.append(GroundingTestCase(
            test_id=f"mhop_{idx:02d}",
            domain=GroundingDomain.MULTIHOP_DEDUCTION,
            partition=part,
            query=f"Trace path from {ent_start} to {ent_end}",
            target_entity=ent_start,
            target_relation="path_to",
            evidence_payload=payload,
            expected_decision=exp_dec,
            expected_value_token=val_token,
            expected_epistemic_state=exp_epist,
        ))

    # Domain 5: Contradiction Deadlock (10 cases)
    for idx in range(10):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 3 else GroundingPartition.DEVELOPMENT
        ent = f"ContestedClaim_{idx}"
        cases.append(GroundingTestCase(
            test_id=f"contra_{idx:02d}",
            domain=GroundingDomain.CONTRADICTION_DEADLOCK,
            partition=part,
            query=f"Is {ent} established as true?",
            target_entity=ent,
            target_relation="truth_value",
            evidence_payload=[
                {"entity": ent, "relation": "truth_value", "value": "True", "polarity": True, "reputation": 0.8},
                {"entity": ent, "relation": "truth_value", "value": "False", "polarity": False, "reputation": 0.8},
            ],
            expected_decision="REPORT_CONFLICT",
            expected_value_token=None,
            expected_epistemic_state="CONFLICTING",
        ))

    # Domain 6: Partial Evidence & Overclaim Guard (10 cases)
    for idx in range(10):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 3 else GroundingPartition.DEVELOPMENT
        ent = f"Company_Partial_{idx}"
        cases.append(GroundingTestCase(
            test_id=f"overclaim_{idx:02d}",
            domain=GroundingDomain.PARTIAL_OVERCLAIM,
            partition=part,
            query=f"Is {ent} completely healthy and flawless?",
            target_entity=ent,
            target_relation="financial health",
            evidence_payload=[
                {"entity": ent, "relation": "Q1 revenue", "value": "+10%", "text": f"{ent} revenue grew 10% in Q1."}
            ],
            expected_decision="QUALIFY",
            expected_value_token=None,
            expected_epistemic_state="PARTIALLY_SUPPORTED",
            expected_is_overclaim_blocked=True,
        ))

    # Domain 7: Wrong-Entity Distractors (10 cases)
    for idx in range(10):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 3 else GroundingPartition.DEVELOPMENT
        target_ent = f"TargetSystem_{idx}"
        wrong_ent = f"IrrelevantSystem_{idx}"
        cases.append(GroundingTestCase(
            test_id=f"wrong_ent_{idx:02d}",
            domain=GroundingDomain.WRONG_ENTITY_DISTRACTOR,
            partition=part,
            query=f"What is status of {target_ent}?",
            target_entity=target_ent,
            target_relation="system status",
            evidence_payload=[
                {"entity": wrong_ent, "relation": "system status", "value": "Operational", "text": f"{wrong_ent} is Operational."}
            ],
            expected_decision="ABSTAIN",
            expected_value_token=None,
            expected_epistemic_state="UNKNOWN",
        ))

    # Domain 8: Irrelevant Noise (10 cases)
    for idx in range(10):
        part = GroundingPartition.FINAL_EVALUATION if idx >= 3 else GroundingPartition.DEVELOPMENT
        ent = f"Device_{idx}"
        cases.append(GroundingTestCase(
            test_id=f"noise_{idx:02d}",
            domain=GroundingDomain.IRRELEVANT_NOISE,
            partition=part,
            query=f"What is firmware version of {ent}?",
            target_entity=ent,
            target_relation="firmware version",
            evidence_payload=[
                {"entity": "WeatherStation", "relation": "humidity", "value": "65%", "text": "Humidity is 65%."}
            ],
            expected_decision="ABSTAIN",
            expected_value_token=None,
            expected_epistemic_state="UNKNOWN",
        ))

    # Separate partitions
    p_cases = [c for c in cases if c.partition == GroundingPartition.PRACTICE]
    d_cases = [c for c in cases if c.partition == GroundingPartition.DEVELOPMENT]
    f_cases = [c for c in cases if c.partition == GroundingPartition.FINAL_EVALUATION]

    return GroundingStressBenchmark(
        benchmark_id="grounding_100_stress_suite",
        total_cases=len(cases),
        practice_cases=p_cases,
        dev_cases=d_cases,
        final_eval_cases=f_cases,
    )
