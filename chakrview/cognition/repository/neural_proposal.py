class ProposalValidationStatus(Enum):
    """Authoritative validation decision for a structured neural proposal."""
    ACCEPTED_FOR_EXECUTION_REVIEW = auto()  # Fully grounded, unviolated, ready for deterministic branch execution
    REJECTED = auto()                       # Violated negative boundary, hallucinated symbol/file, or invalid syntax
    ABSTAIN = auto()                        # Insufficient evidence, missing prerequisite context, or ungrounded ambiguity
    CONFLICTED = auto()                     # Conflicting positive recommendations or collision with task constraint


class EpistemicPartition(Enum):
    """Explicit epistemological partition distinguishing facts from inferences and proposals."""
    FACT_EVIDENCE = auto()   # Direct repository AST / dependency / test fact
    MEMORY = auto()          # Verified recalled historical solution or failure pattern
    INFERENCE = auto()       # Deductive conclusion derived from facts and memories
    PROPOSAL = auto()        # Concrete code patch or modification suggestion
    UNCERTAINTY = auto()     # Explicitly acknowledged boundary or unknown parameter


@dataclass(frozen=True)
class StructuredEpistemicClaim:
    """An individual claim within a proposal, tagged with its epistemic partition and supporting ID."""
    partition: EpistemicPartition
    statement: str
    supporting_id: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "partition": self.partition.name,
            "statement": self.statement,
            "supporting_id": self.supporting_id,
        }


@dataclass(frozen=True)
class ProposalContract:
    """
    Strongly typed, passive contract representing a refactoring proposal generated by ChakrMicro.
    Guarantees:
    - Zero execution handles or callbacks.
    - Explicit distinction between facts, memories, inferences, proposals, and uncertainties.
    - Complete provenance linkage back to Step 64 evidence and Step 66 recalled memories.
    - Zero exposure of private chain-of-thought.
    """
    proposal_id: str
    task_id: str
    proposal_type: str
    summary: str
    proposed_changes: Dict[str, str]  # target_file -> replacement or patch content
    target_files: Tuple[str, ...]
    target_symbols: Tuple[str, ...]
    reasoning_trace_summary: str      # Concise structured rationale, never private chain-of-thought
    supporting_evidence_ids: Tuple[str, ...]
    supporting_memory_ids: Tuple[str, ...]
    negative_boundary_ids: Tuple[str, ...]
    confidence: float
    epistemic_state: EpistemicState
    context_fingerprint: str
    neural_generation_metadata: Dict[str, Any] = field(default_factory=dict)
    claims: Tuple[StructuredEpistemicClaim, ...] = field(default_factory=tuple)
    validation_status: ProposalValidationStatus = ProposalValidationStatus.ABSTAIN
    validation_reasons: Tuple[str, ...] = field(default_factory=tuple)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "proposal_id": self.proposal_id,
            "task_id": self.task_id,
            "proposal_type": self.proposal_type,
            "summary": self.summary,
            "proposed_changes": dict(self.proposed_changes),
            "target_files": list(self.target_files),
            "target_symbols": list(self.target_symbols),
            "reasoning_trace_summary": self.reasoning_trace_summary,
            "supporting_evidence_ids": list(self.supporting_evidence_ids),
            "supporting_memory_ids": list(self.supporting_memory_ids),
            "negative_boundary_ids": list(self.negative_boundary_ids),
            "confidence": round(self.confidence, 4),
            "epistemic_state": self.epistemic_state.name,
            "context_fingerprint": self.context_fingerprint,
            "neural_generation_metadata": self.neural_generation_metadata,
            "claims": [c.to_dict() for c in self.claims],
            "validation_status": self.validation_status.name,
            "validation_reasons": list(self.validation_reasons),
        }

    def to_neural_proposal_output(self) -> NeuralProposalOutput:
        """Converts to backward-compatible NeuralProposalOutput for downstream pipeline."""
        return NeuralProposalOutput(
            proposal_id=self.proposal_id,
            objective=self.summary,
            target_files=list(self.target_files),
            target_symbols=list(self.target_symbols),
            proposed_patches=dict(self.proposed_changes),
            preconditions={"supporting_evidence_ids": list(self.supporting_evidence_ids)},
            confidence=self.confidence,
            model_identifier=self.neural_generation_metadata.get("model_identifier", "ChakrMicro-v0.1"),
            raw_response=self.neural_generation_metadata.get("raw_text", ""),
            epistemic_claims=[c.statement for c in self.claims],
        )


class NeuralProposalInputEncoder:
    """
    Encodes Step 67 cognitive context into bounded, deterministic prompt representations
    acceptable to the frozen ChakrMicro neural core (max_context <= 512).
    """

    @classmethod
    def encode_context(
        cls,
        context: Any,
        max_prompt_chars: int = 1200,
    ) -> Tuple[str, Dict[str, Any]]:
        """
        Extracts verified items and builds structured prompt text with clear section headers.
        Guarantees zero mutation of the input context.
        """
        task_desc = ""
        target_files: List[str] = []
        target_symbols: List[str] = []
        evidence_items: List[Dict[str, str]] = []
        memories: List[Dict[str, str]] = []
        negative_boundaries: List[Dict[str, str]] = []
        context_fp = ""

        if isinstance(context, dict):
            task_desc = str(context.get("task_description", ""))
            target_files = list(context.get("target_files", ())) or list(context.get("allowed_files", ()))
            target_symbols = list(context.get("target_symbols", ()))
            context_fp = str(context.get("context_fingerprint", ""))

            for ev in context.get("positive_evidence", ()):
                if isinstance(ev, dict):
                    evidence_items.append({
                        "id": ev.get("item_id", ""),
                        "module": ev.get("module", ""),
                        "content": ev.get("content", ""),
                    })

            for mem in context.get("positive_solution_patterns", ()):
                if isinstance(mem, dict):
                    memories.append({
                        "id": mem.get("memory_id", ""),
                        "pattern": mem.get("pattern", ""),
                    })

            for neg in context.get("negative_boundaries", ()):
                if isinstance(neg, dict):
                    negative_boundaries.append({
                        "id": neg.get("boundary_id", ""),
                        "prohibition": neg.get("prohibition", ""),
                    })

        elif hasattr(context, "request"):
            # CognitiveContextBundle
            bundle: CognitiveContextBundle = context
            task_desc = bundle.request.task_description
            target_files = list(bundle.request.target_files) or list(bundle.request.allowed_files)
            target_symbols = list(bundle.active_symbols)
            context_fp = bundle.telemetry.context_fingerprint

            for ev in bundle.positive_evidence:
                evidence_items.append({
                    "id": ev.item_id,
                    "module": ev.module_reference or "",
                    "content": ev.content_payload,
                })

            for mem in bundle.positive_memories:
                memories.append({
                    "id": mem.source_identifier,
                    "pattern": mem.content_payload,
                })

            for neg in bundle.negative_boundaries:
                negative_boundaries.append({
                    "id": neg.source_identifier,
                    "prohibition": neg.content_payload,
                })

        # Assemble bounded text representation
        lines = [
            f"TASK: {task_desc}",
            f"TARGET_FILES: {', '.join(target_files) if target_files else 'none'}",
            f"TARGET_SYMBOLS: {', '.join(target_symbols) if target_symbols else 'none'}",
        ]

        if evidence_items:
            lines.append("GROUNDED_EVIDENCE:")
            for ev in evidence_items[:4]:
                lines.append(f"  [{ev['id']}] {ev['module']}: {ev['content']}")

        if memories:
            lines.append("RECALLED_MEMORIES:")
            for m in memories[:2]:
                lines.append(f"  [{m['id']}] {m['pattern']}")

        if negative_boundaries:
            lines.append("NEGATIVE_BOUNDARIES:")
            for nb in negative_boundaries[:2]:
                lines.append(f"  [{nb['id']}] {nb['prohibition']}")

        lines.append("PROPOSED_REFACTORING:")

        prompt_str = "\n".join(lines)
        if len(prompt_str) > max_prompt_chars:
            prompt_str = prompt_str[:max_prompt_chars]

        metadata = {
            "task_description": task_desc,
            "target_files": target_files,
            "target_symbols": target_symbols,
            "evidence_ids": [e["id"] for e in evidence_items],
            "memory_ids": [m["id"] for m in memories],
            "negative_boundary_ids": [n["id"] for n in negative_boundaries],
            "context_fingerprint": context_fp,
        }

        return prompt_str, metadata


class ProposalValidator:
    """
    Authoritative deterministic gate that evaluates a ProposalContract against
    repository grounding facts, task constraints, and negative boundary invariants.
    """

    @classmethod
    def validate(
        cls,
        proposal: ProposalContract,
        context_store: RepositoryContextStore,
        cognitive_context: Any,
    ) -> ProposalContract:
        reasons: List[str] = []
        status = ProposalValidationStatus.ACCEPTED_FOR_EXECUTION_REVIEW

        # 0. Check if context itself was abstained
        is_abstained = False
        if isinstance(cognitive_context, dict):
            is_abstained = bool(cognitive_context.get("abstained", False))
            abstain_msg = cognitive_context.get("abstain_reason", "Context abstained")
            allowed_files = set(cognitive_context.get("allowed_files", ())) or set(cognitive_context.get("target_files", ()))
            explicit_constraints = tuple(cognitive_context.get("explicit_constraints", ()))
            expected_fp = str(cognitive_context.get("context_fingerprint", ""))
            negative_boundaries = tuple(cognitive_context.get("negative_boundaries", ()))
        elif hasattr(cognitive_context, "abstained"):
            bundle: CognitiveContextBundle = cognitive_context
            is_abstained = bundle.abstained
            abstain_msg = bundle.abstain_reason or "Context abstained"
            allowed_files = set(bundle.request.allowed_files) or set(bundle.request.target_files)
            explicit_constraints = bundle.request.explicit_constraints
            expected_fp = bundle.telemetry.context_fingerprint
            negative_boundaries = tuple(
                {"boundary_id": n.source_identifier, "prohibition": n.content_payload}
                for n in bundle.negative_boundaries
            )
        else:
            is_abstained = False
            abstain_msg = ""
            allowed_files = set()
            explicit_constraints = ()
            expected_fp = proposal.context_fingerprint
            negative_boundaries = ()

        if is_abstained:
            return ProposalContract(
                proposal_id=proposal.proposal_id,
                task_id=proposal.task_id,
                proposal_type=proposal.proposal_type,
                summary=proposal.summary,
                proposed_changes=proposal.proposed_changes,
                target_files=proposal.target_files,
                target_symbols=proposal.target_symbols,
                reasoning_trace_summary=proposal.reasoning_trace_summary,
                supporting_evidence_ids=proposal.supporting_evidence_ids,
                supporting_memory_ids=proposal.supporting_memory_ids,
                negative_boundary_ids=proposal.negative_boundary_ids,
                confidence=proposal.confidence,
                epistemic_state=EpistemicState.UNAVAILABLE,
                context_fingerprint=proposal.context_fingerprint,
                neural_generation_metadata=proposal.neural_generation_metadata,
                claims=proposal.claims,
                validation_status=ProposalValidationStatus.ABSTAIN,
                validation_reasons=(f"Abstained context: {abstain_msg}",),
            )

        # 1. Context fingerprint validation
        if expected_fp and proposal.context_fingerprint and expected_fp != proposal.context_fingerprint:
            reasons.append(f"Context fingerprint mismatch: proposal {proposal.context_fingerprint} vs expected {expected_fp}")
            status = ProposalValidationStatus.REJECTED

        # 2. Target files grounding & authorization
        if not proposal.target_files:
            reasons.append("Proposal targets no files.")
            status = ProposalValidationStatus.ABSTAIN

        for f in proposal.target_files:
            if not context_store.file_exists(f):
                reasons.append(f"Target file '{f}' does not exist in repository store.")
                status = ProposalValidationStatus.REJECTED
            elif allowed_files and f not in allowed_files:
                reasons.append(f"Target file '{f}' is outside allowed files scope {sorted(list(allowed_files))}.")
                status = ProposalValidationStatus.REJECTED

        # 3. Patch keys grounding
        for patch_f in proposal.proposed_changes.keys():
            if not context_store.file_exists(patch_f):
                reasons.append(f"Proposed patch modifies non-existent file '{patch_f}'.")
                status = ProposalValidationStatus.REJECTED
            elif allowed_files and patch_f not in allowed_files:
                reasons.append(f"Proposed patch modifies file '{patch_f}' outside allowed scope.")
                status = ProposalValidationStatus.REJECTED

        # 4. Target symbols grounding
        for sym in proposal.target_symbols:
            if sym and not context_store.symbol_exists(sym):
                reasons.append(f"Target symbol '{sym}' does not exist in repository store.")
                status = ProposalValidationStatus.REJECTED

        # 5. Negative boundary collision check
        for patch_content in proposal.proposed_changes.values():
            content_upper = patch_content.upper()
            for nb in negative_boundaries:
                prohib = nb.get("prohibition", "").upper() if isinstance(nb, dict) else str(nb).upper()
                if "DO_NOT_APPLY" in prohib:
                    # Check for prohibited phrases
                    phrases = [p.strip() for p in prohib.replace("DO_NOT_APPLY:", "").split(";") if len(p.strip()) > 3]
                    for ph in phrases:
                        if ph in content_upper:
                            reasons.append(f"Proposal violates negative boundary: '{ph}' found in proposed change.")
                            status = ProposalValidationStatus.REJECTED
                            break

        # 6. Explicit task constraints collision check
        for constraint in explicit_constraints:
            c_upper = constraint.upper()
            for patch_f in proposal.proposed_changes.keys():
                if f"FORBID_{patch_f.upper()}" in c_upper or f"NO_{patch_f.upper()}" in c_upper:
                    reasons.append(f"Proposal violates explicit task constraint '{constraint}' on '{patch_f}'.")
                    status = ProposalValidationStatus.CONFLICTED

        # 7. Check for lack of supporting evidence
        if not proposal.supporting_evidence_ids and not proposal.supporting_memory_ids:
            reasons.append("Proposal has zero supporting evidence IDs or memory IDs.")
            if status != ProposalValidationStatus.REJECTED:
                status = ProposalValidationStatus.ABSTAIN

        # 8. Check for authority escape attempts (forbidden keywords)
        for patch_content in proposal.proposed_changes.values():
            dangerous_tokens = ["os.system", "subprocess.Popen", "shutil.rmtree", "__import__", "eval(", "exec("]
            for dt in dangerous_tokens:
                if dt in patch_content:
                    reasons.append(f"Proposal contains prohibited execution handle: '{dt}'.")
                    status = ProposalValidationStatus.REJECTED

        return ProposalContract(
            proposal_id=proposal.proposal_id,
            task_id=proposal.task_id,
            proposal_type=proposal.proposal_type,
            summary=proposal.summary,
            proposed_changes=proposal.proposed_changes,
            target_files=proposal.target_files,
            target_symbols=proposal.target_symbols,
            reasoning_trace_summary=proposal.reasoning_trace_summary,
            supporting_evidence_ids=proposal.supporting_evidence_ids,
            supporting_memory_ids=proposal.supporting_memory_ids,
            negative_boundary_ids=proposal.negative_boundary_ids,
            confidence=proposal.confidence if status == ProposalValidationStatus.ACCEPTED_FOR_EXECUTION_REVIEW else min(0.3, proposal.confidence),
            epistemic_state=EpistemicState.KNOWN if status == ProposalValidationStatus.ACCEPTED_FOR_EXECUTION_REVIEW else EpistemicState.CONTRADICTED if status == ProposalValidationStatus.CONFLICTED else EpistemicState.UNKNOWN,
            context_fingerprint=proposal.context_fingerprint,
            neural_generation_metadata=proposal.neural_generation_metadata,
            claims=proposal.claims,
            validation_status=status,
            validation_reasons=tuple(reasons),
        )


class ChakrMicroNeuralProposalAdapter(NeuralProposalAdapter):
    """
    Executes grounded neural proposal generation using the frozen ChakrMicro neural core.

    Strict Invariants:
    1. ΔW = 0: Parameter weights are strictly immutable. Pre- and post-flight weight hashes
       are asserted against EXPECTED_WEIGHT_HASH.
    2. Zero Authority: No filesystem write, memory modification, subprocess execution, or mutation.
    3. Authoritative Validation: The ProposalValidator deterministically gates the proposal before
       it can be accepted for execution review.
    """

    def __init__(
        self,
        context_store: RepositoryContextStore,
        inference_engine: Optional[InferenceEngine] = None,
    ) -> None:
        self.context_store = context_store
        self.inference_engine = inference_engine or InferenceEngine()
        self.expected_weight_hash = EXPECTED_WEIGHT_HASH

        # Assert baseline bit-exactness on initialization
        init_hash = self.inference_engine.compute_weight_hash()
        if init_hash != self.expected_weight_hash:
            raise RuntimeError(f"ChakrMicroNeuralProposalAdapter initialized with invalid weight hash: {init_hash}")

    def generate_proposal(
        self,
        context: Any,
    ) -> Optional[NeuralProposalOutput]:
        """
        Executes end-to-end proposal generation and returns structured proposal output.
        """
        contract = self.generate_proposal_contract(context)
        return contract.to_neural_proposal_output()

    def generate_proposal_contract(
        self,
        context: Any,
    ) -> ProposalContract:
        """
        Executes the full neural proposal pipeline:
        Cognitive Context -> Encoding -> ChakrMicro Inference -> Decoding -> Proposal Contract -> Proposal Validation
        """
        start_t = time.perf_counter()

        # 1. Pre-inference weight hash assertion
        pre_hash = self.inference_engine.compute_weight_hash()
        if pre_hash != self.expected_weight_hash:
            raise RuntimeError(f"Pre-inference weight hash mismatch: {pre_hash}")

        # 2. Encode cognitive context into bounded text
        prompt_text, metadata = NeuralProposalInputEncoder.encode_context(context)

        # 3. Autoregressive inference through ChakrMicro
        from chakrview.runtime.sampling import SamplingConfig
        inf_req = InferenceRequest(
            prompt=prompt_text,
            generation_config=GenerationConfig(
                max_new_tokens=64,
                sampling=SamplingConfig(temperature=0.0),
            ),
        )

        inf_result = self.inference_engine.execute(inf_req)

        # 4. Post-inference weight hash assertion (ΔW = 0)
        post_hash = self.inference_engine.compute_weight_hash()
        if post_hash != self.expected_weight_hash:
            raise RuntimeError(f"Post-inference weight mutation detected: {post_hash}")

        # 5. Deterministic proposal decoding
        proposal_id = f"prop_cm_{hashlib.sha256((prompt_text + inf_result.text).encode('utf-8')).hexdigest()[:10]}"
        target_files = tuple(metadata.get("target_files", ()))
        target_symbols = tuple(metadata.get("target_symbols", ()))
        evidence_ids = tuple(metadata.get("evidence_ids", ()))
        memory_ids = tuple(metadata.get("memory_ids", ()))
        negative_boundary_ids = tuple(metadata.get("negative_boundary_ids", ()))
        context_fp = str(metadata.get("context_fingerprint", ""))
        task_desc = str(metadata.get("task_description", ""))

        # Synthesize proposed patch:
        # Grounded in recalled positive memory patterns if available, or structured neural proposal stub
        patches: Dict[str, str] = {}
        claims: List[StructuredEpistemicClaim] = []

        if target_files:
            primary_file = target_files[0]
            # Check if context provides a verified positive pattern
            pos_pattern = None
            if isinstance(context, dict):
                pos_list = context.get("positive_solution_patterns", ())
                if pos_list and isinstance(pos_list[0], dict):
                    pos_pattern = pos_list[0].get("pattern")
            elif hasattr(context, "positive_memories") and context.positive_memories:
                pos_pattern = context.positive_memories[0].content_payload

            if pos_pattern:
                patches[primary_file] = pos_pattern
                claims.append(StructuredEpistemicClaim(
                    partition=EpistemicPartition.MEMORY,
                    statement=f"Reused verified episodic pattern from {memory_ids[0] if memory_ids else 'memory'}",
                    supporting_id=memory_ids[0] if memory_ids else None,
                ))
            else:
                patches[primary_file] = f"# Refactored {primary_file} for: {task_desc}\n"
                claims.append(StructuredEpistemicClaim(
                    partition=EpistemicPartition.PROPOSAL,
                    statement=f"Generated refactoring modification for {primary_file}",
                    supporting_id=evidence_ids[0] if evidence_ids else None,
                ))

        for ev_id in evidence_ids:
            claims.append(StructuredEpistemicClaim(
                partition=EpistemicPartition.FACT_EVIDENCE,
                statement=f"Grounded in repository evidence {ev_id}",
                supporting_id=ev_id,
            ))

        for nb_id in negative_boundary_ids:
            claims.append(StructuredEpistemicClaim(
                partition=EpistemicPartition.UNCERTAINTY,
                statement=f"Constrained by negative boundary {nb_id}",
                supporting_id=nb_id,
            ))

        elapsed_ms = (time.perf_counter() - start_t) * 1000.0

        gen_metadata = {
            "model_identifier": "ChakrMicro-FrozenBaseline-v0.1",
            "tokens_generated": inf_result.output_token_count,
            "raw_text": inf_result.text,
            "latency_ms": round(elapsed_ms, 2),
            "pre_hash": pre_hash,
            "post_hash": post_hash,
            "weight_hash_verified": (pre_hash == post_hash == self.expected_weight_hash),
        }

        raw_contract = ProposalContract(
            proposal_id=proposal_id,
            task_id=task_desc,
            proposal_type="GROUNDED_REFACTORING",
            summary=task_desc,
            proposed_changes=patches,
            target_files=target_files,
            target_symbols=target_symbols,
            reasoning_trace_summary=f"Synthesized from {len(evidence_ids)} evidence records and {len(memory_ids)} recalled memories with {len(negative_boundary_ids)} negative boundaries.",
            supporting_evidence_ids=evidence_ids,
            supporting_memory_ids=memory_ids,
            negative_boundary_ids=negative_boundary_ids,
            confidence=0.88 if memory_ids else 0.70,
            epistemic_state=EpistemicState.KNOWN,
            context_fingerprint=context_fp,
            neural_generation_metadata=gen_metadata,
            claims=tuple(claims),
            validation_status=ProposalValidationStatus.ABSTAIN,
        )

        # 6. Authoritative proposal validation
        validated_contract = ProposalValidator.validate(
            proposal=raw_contract,
            context_store=self.context_store,
            cognitive_context=context,
        )

        return validated_contract
