# 6. Elementary Arithmetic (Balanced and precise)
arithmetic_examples = []
for a in range(1, 21):
    for b in range(1, 21):
        # Addition
        arithmetic_examples.append((f"What is {a} + {b}?", f" {a} + {b} = {a + b}."))
        arithmetic_examples.append((f"Calculate: {a} plus {b}", f" {a} plus {b} is {a + b}."))
        # Subtraction
        if a >= b:
            arithmetic_examples.append((f"What is {a} - {b}?", f" {a} - {b} = {a - b}."))
            arithmetic_examples.append((f"If you have {a} apples and give away {b}, how many remain?", f" You will have {a - b} apples left."))
        # Multiplication (smaller numbers)
        if a <= 12 and b <= 12:
            arithmetic_examples.append((f"What is {a} * {b}?", f" {a} * {b} = {a * b}."))


def build_dataset():
    records = []
    
    # 1. Add conversational variants
    for q, a in conversational_templates:
        for prefix in ["", "Please answer: ", "Kindly tell me: ", "Hello: "]:
            records.append({
                "prompt": f"User: {prefix}{q}\nAssistant:",
                "target": f" {a}",
                "category": "English Conversation"
            })
            
    # 2. Add explanations
    for q, a in explanations:
        for prefix in ["", "Explain: ", "Can you describe: ", "Please explain: "]:
            records.append({
                "prompt": f"User: {prefix}{q}\nAssistant:",
                "target": f" {a}",
                "category": "English Explanations"
            })
            
    # 3. Add Hindi
    for q, a in hindi_dialogue:
        for prefix in ["", "सरल शब्दों में बताइए: ", "कृपया उत्तर दें: ", "स्पष्ट कीजिए: "]:
            records.append({
                "prompt": f"User: {prefix}{q}\nAssistant:",
                "target": f" {a}",
                "category": "Devanagari Hindi"
            })
            
    # 4. Add Hinglish
    for q, a in hinglish_tech:
        for prefix in ["", "Please explain: ", "Short me batao: ", "Arre bhai: "]:
            records.append({
                "prompt": f"User: {prefix}{q}\nAssistant:",
                "target": f" {a}",
                "category": "Hinglish"
            })
            
    # 5. Add exact copying
    for phrase in copy_phrases:
        for cmd in ["Say exactly: ", "Repeat verbatim: ", "Copy this sentence: ", "Echo: "]:
            records.append({
                "prompt": f"User: {cmd}{phrase}\nAssistant:",
                "target": f" {phrase}",
                "category": "Exact Copying"
            })
            
    # 6. Sample arithmetic
    random.seed(42)
    sample_arith = random.sample(arithmetic_examples, min(600, len(arithmetic_examples)))
    for q, a in sample_arith:
        records.append({
            "prompt": f"User: {q}\nAssistant:",
            "target": a,
            "category": "Elementary Arithmetic"
        })
        
    random.shuffle(records)
    split_idx = int(len(records) * 0.9)
    train_records = records[:split_idx]
    val_records = records[split_idx:]
    
    with open(OUT_TRAIN, "w", encoding="utf-8") as f:
        for r in train_records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
            
    with open(OUT_VAL, "w", encoding="utf-8") as f:
        for r in val_records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
            
    print(f"Generated clean balanced dataset:")
    print(f"  Train samples: {len(train_records)} -> {OUT_TRAIN}")
    print(f"  Val samples:   {len(val_records)} -> {OUT_VAL}")


if __name__ == "__main__":
    build_dataset()
